import path from "node:path";
import { gzipSync } from "node:zlib";

import {
  FeatherProjectConfigSchema,
  type AgentDefinitionConfig,
  type FeatherProjectConfig,
  type ModuleReferenceConfig,
} from "../types/config.js";

export interface BuildAgentPackageOptions {
  config: FeatherProjectConfig;
  agent?: string;
  packageName?: string;
}

export interface BuildAgentPackageResult {
  filename: string;
  mimeType: string;
  archive: Buffer;
  agentName: string;
  scaffoldedModules: string[];
}

type ScaffoldKind = "provider" | "tool" | "memory" | "planner" | "hook" | "context";

interface ScaffoldSpec {
  modulePath: string;
  kind: ScaffoldKind;
  label: string;
  exportName?: string;
  mode?: number;
}

interface RewriteState {
  counter: number;
  scaffoldsByPath: Map<string, ScaffoldSpec>;
  rewrittenModulePaths: Map<string, string>;
}

interface ArchiveFile {
  path: string;
  content: string | Buffer;
  mode?: number;
}

const PACKAGE_MIME_TYPE = "application/gzip";

export function buildAgentPackage(options: BuildAgentPackageOptions): BuildAgentPackageResult {
  const validated = FeatherProjectConfigSchema.parse(options.config);
  const config = cloneConfig(validated);
  const agentName = resolveAgentName(config, options.agent);
  config.defaults = config.defaults ?? {};
  config.defaults.agent = agentName;

  const rewriteState: RewriteState = {
    counter: 0,
    scaffoldsByPath: new Map<string, ScaffoldSpec>(),
    rewrittenModulePaths: new Map<string, string>(),
  };
  rewriteConfigModulePaths(config, rewriteState);

  const safePackageName = sanitisePackageName(options.packageName ?? `legionaire-${agentName}`);
  const envVars = collectConfigEnvVars(config);
  const scaffoldFiles = Array.from(rewriteState.scaffoldsByPath.values())
    .sort((a, b) => a.modulePath.localeCompare(b.modulePath))
    .map((spec) => ({
      path: toArchivePath(spec.modulePath),
      content: buildScaffoldContent(spec),
      mode: spec.mode ?? 0o644,
    }));

  const files: ArchiveFile[] = [
    {
      path: "package.json",
      content: `${JSON.stringify(buildPackageJson(safePackageName), null, 2)}\n`,
    },
    {
      path: "README.md",
      content: buildReadme({
        packageName: safePackageName,
        agentName,
        envVars,
        scaffolds: scaffoldFiles.map((file) => file.path),
      }),
    },
    {
      path: ".gitignore",
      content: "node_modules/\n.env\n",
    },
    {
      path: ".env.example",
      content: envVars.length > 0 ? envVars.map((name) => `${name}=`).join("\n") + "\n" : "# No runtime environment variables required.\n",
    },
    {
      path: "legionaire.config.json",
      content: `${JSON.stringify(config, null, 2)}\n`,
    },
    {
      path: "src/run-agent.mjs",
      content: buildRunnerScript(agentName),
      mode: 0o755,
    },
    ...scaffoldFiles,
  ];

  const tar = buildTarArchive(files);
  const archive = gzipSync(tar);

  return {
    filename: `${safePackageName}.tar.gz`,
    mimeType: PACKAGE_MIME_TYPE,
    archive,
    agentName,
    scaffoldedModules: scaffoldFiles.map((file) => file.path),
  };
}

function buildPackageJson(packageName: string) {
  return {
    name: packageName,
    private: true,
    version: "0.0.0",
    type: "module",
    scripts: {
      start: "node src/run-agent.mjs",
    },
    dependencies: {
      "legionaire": "latest",
    },
  };
}

function buildReadme(options: {
  packageName: string;
  agentName: string;
  envVars: string[];
  scaffolds: string[];
}): string {
  const envSection = options.envVars.length > 0
    ? `2. Copy \`.env.example\` to \`.env\` and set:\n${options.envVars.map((name) => `   - \`${name}\``).join("\n")}\n`
    : "2. No runtime environment variables are required for this configuration.\n";
  const scaffoldSection = options.scaffolds.length > 0
    ? `\n## Modules Requiring Implementation\n\nThe following scaffold modules were generated because your configuration referenced local modules:\n${options.scaffolds.map((file) => `- \`${file}\``).join("\n")}\n`
    : "";
  return `# ${options.packageName}

This package was generated by the Legionaire dashboard for agent \`${options.agentName}\`.

## Quick Start

1. Install dependencies:
   \`\`\`bash
   npm install
   \`\`\`
${envSection}
3. Run the agent:
   \`\`\`bash
   npm start -- "Summarize Legionaire in one sentence."
   \`\`\`

The runtime config lives in \`legionaire.config.json\`. The entrypoint script is \`src/run-agent.mjs\`.
${scaffoldSection}`;
}

function buildRunnerScript(agentName: string): string {
  return `import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { createAgent } from "legionaire";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const configPath = path.resolve(__dirname, "../legionaire.config.json");
const envPath = path.resolve(__dirname, "../.env");

loadDotEnv(envPath);

async function main() {
  const prompt = process.argv.slice(2).join(" ") || "Hello from Legionaire";
  const { agent } = await createAgent({ config: configPath, agent: ${JSON.stringify(agentName)} });
  const result = await agent.run({
    sessionId: \`dashboard-export-\${Date.now()}\`,
    input: { role: "user", content: prompt },
  });
  console.log(JSON.stringify(result, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});

function loadDotEnv(filePath) {
  if (!fs.existsSync(filePath)) {
    return;
  }
  const raw = fs.readFileSync(filePath, "utf8");
  for (const line of raw.split(/\\r?\\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }
    const idx = trimmed.indexOf("=");
    if (idx <= 0) {
      continue;
    }
    const key = trimmed.slice(0, idx).trim();
    if (!key || process.env[key] !== undefined) {
      continue;
    }
    let value = trimmed.slice(idx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    process.env[key] = value;
  }
}
`;
}

function rewriteConfigModulePaths(config: FeatherProjectConfig, state: RewriteState): void {
  for (const [providerName, definition] of Object.entries(config.providers.entries ?? {})) {
    rewriteReference(definition, "provider", `providers.${providerName}`, state);
  }
  if (config.defaults?.providers) {
    rewriteReference(config.defaults.providers, "provider", "defaults.providers", state);
  }

  for (const [toolName, definition] of Object.entries(config.tools ?? {})) {
    rewriteReference(definition, "tool", `tools.${toolName}`, state);
  }
  if (config.defaults?.tools) {
    rewriteReference(config.defaults.tools, "tool", "defaults.tools", state);
  }

  for (const [agentName, definition] of Object.entries(config.agents ?? {})) {
    rewriteAgentDefinition(definition, `agents.${agentName}`, state);
  }
  if (config.defaults?.agentConfig) {
    rewriteAgentDefinition(config.defaults.agentConfig as AgentDefinitionConfig, "defaults.agentConfig", state);
  }
}

function rewriteAgentDefinition(definition: AgentDefinitionConfig, labelPrefix: string, state: RewriteState): void {
  if (definition.planner && typeof definition.planner === "object" && ("module" in definition.planner || "builtin" in definition.planner)) {
    rewriteReference(definition.planner as ModuleReferenceConfig, "planner", `${labelPrefix}.planner`, state);
  }
  if (definition.memory) {
    rewriteReference(definition.memory, "memory", `${labelPrefix}.memory`, state);
  }
  if (definition.context?.builder) {
    rewriteReference(definition.context.builder, "context", `${labelPrefix}.context.builder`, state);
  }
  if (definition.policies) {
    rewriteReference(definition.policies, "hook", `${labelPrefix}.policies`, state);
  }
  if (definition.quotas) {
    rewriteReference(definition.quotas, "hook", `${labelPrefix}.quotas`, state);
  }
  if (definition.toolCache) {
    rewriteReference(definition.toolCache, "hook", `${labelPrefix}.toolCache`, state);
  }
  if (definition.shouldStop) {
    rewriteReference(definition.shouldStop, "hook", `${labelPrefix}.shouldStop`, state);
  }
  if (definition.createMemoryTurn) {
    rewriteReference(definition.createMemoryTurn, "hook", `${labelPrefix}.createMemoryTurn`, state);
  }
  if (Array.isArray(definition.tools)) {
    const toolEntries = definition.tools as Array<string | ModuleReferenceConfig>;
    definition.tools = toolEntries.map((toolEntry: string | ModuleReferenceConfig, index: number) => {
      if (!toolEntry || typeof toolEntry !== "object") {
        return toolEntry;
      }
      rewriteReference(toolEntry as ModuleReferenceConfig, "tool", `${labelPrefix}.tools[${index}]`, state);
      return toolEntry;
    });
  }
}

function rewriteReference(reference: ModuleReferenceConfig, kind: ScaffoldKind, label: string, state: RewriteState): void {
  if (!reference || typeof reference !== "object" || typeof reference.module !== "string") {
    return;
  }
  if (!reference.module.startsWith(".")) {
    return;
  }
  const modulePath = sanitiseRelativeModulePath(reference.module, state);
  reference.module = modulePath;
  if (!state.scaffoldsByPath.has(modulePath)) {
    state.scaffoldsByPath.set(modulePath, {
      modulePath,
      kind,
      label,
      exportName: typeof reference.export === "string" ? reference.export : undefined,
    });
  }
}

function collectConfigEnvVars(config: FeatherProjectConfig): string[] {
  const names = new Set<string>();
  collectEnvLikeKeys(config, names);

  const entries = config.providers.entries ?? {};
  for (const [providerName, definition] of Object.entries(entries) as Array<[string, FeatherProjectConfig["providers"]["entries"][string]]>) {
    if (definition.apiKeyEnv && definition.apiKeyEnv.trim()) {
      names.add(definition.apiKeyEnv.trim());
      continue;
    }
    names.add(`${toEnvToken(providerName)}_API_KEY`);
  }
  return Array.from(names).sort();
}

function collectEnvLikeKeys(value: unknown, names: Set<string>): void {
  if (Array.isArray(value)) {
    value.forEach((entry) => collectEnvLikeKeys(entry, names));
    return;
  }
  if (!value || typeof value !== "object") {
    return;
  }
  for (const [key, entry] of Object.entries(value as Record<string, unknown>)) {
    if (typeof entry === "string" && key.endsWith("Env") && entry.trim()) {
      names.add(entry.trim());
      continue;
    }
    collectEnvLikeKeys(entry, names);
  }
}

function toEnvToken(value: string): string {
  const token = value.toUpperCase().replace(/[^A-Z0-9]+/g, "_").replace(/^_+|_+$/g, "");
  return token || "PROVIDER";
}

function buildScaffoldContent(spec: ScaffoldSpec): string {
  const message = `TODO: Implement ${spec.kind} module for '${spec.label}'`;
  const exportName = normaliseExportName(spec.exportName);
  if (spec.kind === "tool") {
    const toolName = inferToolNameFromPath(spec.modulePath);
    const named = exportName ? `\nexport const ${exportName} = createToolFactory;\n` : "";
    return `const errorMessage = ${JSON.stringify(message)};

function createToolFactory() {
  return {
    name: ${JSON.stringify(toolName)},
    description: "Scaffolded tool. Replace with your implementation.",
    async run() {
      throw new Error(errorMessage);
    },
  };
}

export default createToolFactory;${named}`;
  }

  const named = exportName ? `\nexport const ${exportName} = createScaffold;\n` : "";
  return `const errorMessage = ${JSON.stringify(message)};

function createScaffold() {
  throw new Error(errorMessage);
}

export default createScaffold;${named}`;
}

function inferToolNameFromPath(modulePath: string): string {
  const base = path.posix.basename(modulePath).replace(/\.[^.]+$/, "");
  const cleaned = base.replace(/[^a-zA-Z0-9_-]+/g, "-");
  return cleaned || "scaffold-tool";
}

function normaliseExportName(exportName: string | undefined): string | null {
  if (!exportName || exportName === "default") {
    return null;
  }
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(exportName)) {
    return null;
  }
  return exportName;
}

function sanitiseRelativeModulePath(modulePath: string, state: RewriteState): string {
  const raw = modulePath.replace(/\\/g, "/");
  const sourceKey = path.posix.normalize(raw);
  const cached = state.rewrittenModulePaths.get(sourceKey);
  if (cached) {
    return cached;
  }
  let normalised = path.posix.normalize(raw);
  if (normalised.startsWith("/")) {
    normalised = "";
  }
  const isSafeRelative = normalised.length > 0 && normalised !== "." && !normalised.startsWith("../");
  const preferred = isSafeRelative
    ? (normalised.startsWith("./") ? normalised : `./${normalised}`)
    : `./scaffolds/module-${++state.counter}.js`;
  const withExtension = preferred.endsWith(".js") || preferred.endsWith(".mjs") || preferred.endsWith(".cjs")
    ? preferred
    : `${preferred}.js`;
  if (!state.scaffoldsByPath.has(withExtension)) {
    state.rewrittenModulePaths.set(sourceKey, withExtension);
    return withExtension;
  }
  let suffix = 2;
  let candidate = withExtension.replace(/\.([cm]?js)$/i, `-${suffix}.$1`);
  while (state.scaffoldsByPath.has(candidate)) {
    suffix += 1;
    candidate = withExtension.replace(/\.([cm]?js)$/i, `-${suffix}.$1`);
  }
  state.rewrittenModulePaths.set(sourceKey, candidate);
  return candidate;
}

function toArchivePath(modulePath: string): string {
  return modulePath.replace(/^\.\//, "");
}

function resolveAgentName(config: FeatherProjectConfig, requested?: string): string {
  const names = Object.keys(config.agents ?? {});
  if (requested) {
    if (!(requested in config.agents)) {
      throw new Error(`Agent '${requested}' not found in configuration`);
    }
    return requested;
  }
  if (config.defaults?.agent && config.defaults.agent in config.agents) {
    return config.defaults.agent;
  }
  if (names.length > 0) {
    return names[0];
  }
  throw new Error("Configuration must define at least one agent to export a package");
}

function cloneConfig(config: FeatherProjectConfig): FeatherProjectConfig {
  return JSON.parse(JSON.stringify(config)) as FeatherProjectConfig;
}

function sanitisePackageName(input: string): string {
  const slug = input
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/^[._-]+/, "");
  return slug || "legionaire-package";
}

function buildTarArchive(files: ArchiveFile[]): Buffer {
  const chunks: Buffer[] = [];
  for (const file of files) {
    const content = Buffer.isBuffer(file.content) ? file.content : Buffer.from(file.content, "utf8");
    const entryPath = path.posix.normalize(file.path).replace(/^\/+/, "");
    const header = createTarHeader({
      path: entryPath,
      size: content.length,
      mode: file.mode ?? 0o644,
      mtime: Math.floor(Date.now() / 1000),
    });
    chunks.push(header, content);
    const padding = (512 - (content.length % 512)) % 512;
    if (padding > 0) {
      chunks.push(Buffer.alloc(padding, 0));
    }
  }
  chunks.push(Buffer.alloc(1024, 0));
  return Buffer.concat(chunks);
}

function createTarHeader(options: { path: string; size: number; mode: number; mtime: number }): Buffer {
  const header = Buffer.alloc(512, 0);
  const { name, prefix } = splitTarPath(options.path);

  writeString(header, 0, 100, name);
  writeOctal(header, 100, 8, options.mode);
  writeOctal(header, 108, 8, 0);
  writeOctal(header, 116, 8, 0);
  writeOctal(header, 124, 12, options.size);
  writeOctal(header, 136, 12, options.mtime);
  writeString(header, 148, 8, "        ");
  writeString(header, 156, 1, "0");
  writeString(header, 257, 6, "ustar");
  writeString(header, 263, 2, "00");
  writeString(header, 265, 32, "legionaire");
  writeString(header, 297, 32, "legionaire");
  writeString(header, 345, 155, prefix);

  let checksum = 0;
  for (const byte of header) {
    checksum += byte;
  }
  const checksumText = `${checksum.toString(8).padStart(6, "0")}\0 `;
  writeString(header, 148, 8, checksumText);

  return header;
}

function splitTarPath(filePath: string): { name: string; prefix: string } {
  if (filePath.length <= 100) {
    return { name: filePath, prefix: "" };
  }
  for (let i = filePath.length - 1; i >= 0; i -= 1) {
    if (filePath[i] !== "/") {
      continue;
    }
    const prefix = filePath.slice(0, i);
    const name = filePath.slice(i + 1);
    if (name.length <= 100 && prefix.length <= 155) {
      return { name, prefix };
    }
  }
  throw new Error(`Archive path '${filePath}' is too long for tar format`);
}

function writeString(target: Buffer, offset: number, length: number, value: string): void {
  const data = Buffer.from(value, "utf8");
  data.copy(target, offset, 0, Math.min(length, data.length));
}

function writeOctal(target: Buffer, offset: number, length: number, value: number): void {
  const text = value.toString(8).padStart(length - 1, "0");
  writeString(target, offset, length, `${text}\0`);
}
